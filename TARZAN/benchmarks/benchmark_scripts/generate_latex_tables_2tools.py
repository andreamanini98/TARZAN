#!/usr/bin/env python3
"""
generate_latex_tables_2tools.py

Same tables as generate_latex_tables.py, with two differences:
  - only TARZAN and UPPAAL (the TChecker block is dropped);
  - in every row the better of the two values is set in bold, for the
    execution time (ET) and for the regions/states count. Lower is better.

Parsing and number formatting are reused from generate_latex_tables.py, so the
figures are identical to the ones that script produces.

Run it from this directory, after generate_benchmark_summary.sh:
    python3 generate_latex_tables_2tools.py
"""

import re
import sys
from pathlib import Path

from generate_latex_tables import (parse_benchmark_summary, format_value,
                                   format_time_value, extract_n_from_instance,
                                   generate_complete_latex_document)

SUMMARY = "../../../output/benchmark_summary.txt"
OUT_DIR = Path("../../../output/latex_results")


def numeric(cell: str):
    """The comparable value of a formatted cell, or None when not comparable."""
    if cell is None:
        return None
    if "epsilon" in cell:          # below 0.001 s: the smallest value there is
        return 0.0
    try:
        return float(cell.replace(",", ""))
    except ValueError:
        return None                # TO, OOM, ---


def emphasise(a: str, b: str):
    """Bold whichever of the two cells is better (smaller). A value that exists
    always beats TO/OOM/---; two non-comparable or equal values get no bold."""
    va, vb = numeric(a), numeric(b)
    if va is None and vb is None:
        return a, b
    if vb is None:
        return rf"\textbf{{{a}}}", b
    if va is None:
        return a, rf"\textbf{{{b}}}"
    if va < vb:
        return rf"\textbf{{{a}}}", b
    if vb < va:
        return a, rf"\textbf{{{b}}}"
    return a, b


def tool_cells(res, kind: str):
    """The four cells VT, ET, Mem, Regions/States for one tool."""
    if res.timeout:
        return ["TO", "TO", "---", "---"]
    if res.failed:
        return ["---", "---", "OOM", "---"]
    if kind == "tarzan":
        vt, mem, count = res.total_time, res.peak_memory, res.num_regions
        et_ms = res.exec_time
    else:
        vt, mem, count = res.cpu_time_s, res.resident_memory, res.states_explored
        et_ms = res.uppaal_exec_time
    et = "---"
    if et_ms:
        try:
            et = format_time_value(str(float(et_ms) / 1000), "---")
        except (TypeError, ValueError):
            et = "---"
    return [format_time_value(vt, "---"), et, format_value(mem, "---"), format_value(count, "---")]


def table(experiment) -> str:
    L = [r"\definecolor{lightgray}{gray}{0.95}",
         r"\setlength{\aboverulesep}{1pt}",
         r"\setlength{\belowrulesep}{1pt}",
         r"{\renewcommand{\arraystretch}{0.95}",
         r"{\setlength{\tabcolsep}{3.25pt}",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Benchmark results for \texttt{" + experiment.name.replace("_", r"\_") + r"}}",
         r"\label{tab:" + experiment.name + r"-2t}",
         r"\resizebox{\textwidth}{!}{",
         r"\begin{tabular}{%", r"    c|rrrr|rrrr", r"}", r"\toprule",
         r"\multirow{2}{*}{\textbf{K}}",
         r"  & \multicolumn{4}{c|}{\textbf{TARZAN}}",
         r"  & \multicolumn{4}{c}{\textbf{UPPAAL}} \\",
         r"  & \multicolumn{1}{c}{\textbf{VT}}",
         r"  & \multicolumn{1}{c}{\textbf{ET}}",
         r"  & \multicolumn{1}{c}{\textbf{Mem}}",
         r"  & \multicolumn{1}{c|}{\textbf{Regions}}",
         r"  & \multicolumn{1}{c}{\textbf{VT}}",
         r"  & \multicolumn{1}{c}{\textbf{ET}}",
         r"  & \multicolumn{1}{c}{\textbf{Mem}}",
         r"  & \multicolumn{1}{c}{\textbf{States}} \\",
         r"\midrule"]

    for i, sub in enumerate(experiment.sub_experiments):
        L.append(r"\rowcolor{" + ("white" if i % 2 == 0 else "lightgray") + r"}")
        t = tool_cells(sub.tarzan, "tarzan")
        u = tool_cells(sub.uppaal, "uppaal")
        t[1], u[1] = emphasise(t[1], u[1])          # ET
        t[3], u[3] = emphasise(t[3], u[3])          # regions vs states
        L.append(f"{extract_n_from_instance(sub.name)}  & " + " & ".join(t))
        L.append(r"   & " + " & ".join(u) + r" \\")

    L += [r"\bottomrule", r"\end{tabular}", r"}", r"\end{table}", r"}", r"}", ""]
    return "\n".join(L)


def main():
    if not Path(SUMMARY).exists():
        print(f"Error: summary not found: {SUMMARY}"); sys.exit(1)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    experiments = parse_benchmark_summary(SUMMARY)

    head = ["% LaTeX tables generated from benchmark results (TARZAN vs UPPAAL)",
            "% Generated by generate_latex_tables_2tools.py",
            "%",
            "% Legend:",
            "%   VT  = verification time (s)",
            "%   ET  = total execution time (s)",
            "%   Mem = peak memory, MaxRSS (MB)",
            "%   Bold marks the better of the two tools on ET and on regions/states.",
            "%   --- not available   OOM out of memory   TO timeout",
            "%   $\\epsilon$ = below 0.001 s",
            "%",
            "% Requires: booktabs, multirow, colortbl (or xcolor with table), graphicx",
            ""]
    body = [table(e) for e in experiments]
    tables = "\n".join(head + body)
    (OUT_DIR / "benchmark_tables_2tools.tex").write_text(tables, encoding="utf-8")
    (OUT_DIR / "benchmark_results_2tools.tex").write_text(
        generate_complete_latex_document(tables), encoding="utf-8")
    print(f"{len(experiments)} tables -> {OUT_DIR/'benchmark_tables_2tools.tex'}")
    print(f"{' ':17}  -> {OUT_DIR/'benchmark_results_2tools.tex'} (compilabile)")


if __name__ == "__main__":
    main()
